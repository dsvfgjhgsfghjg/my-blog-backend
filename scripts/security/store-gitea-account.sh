#!/usr/bin/env bash
set -euo pipefail

if ! { exec 3<>/dev/tty; } 2>/dev/null; then
  echo "Run this command from an interactive local terminal" >&2
  exit 1
fi

default_username="${GITEA_USERNAME:-leoxiao}"
default_url="${GITEA_URL:-https://leo-blog.top/gitea}"
config_dir="${XDG_CONFIG_HOME:-$HOME/.config}/myblog"
env_file="${GITEA_ENV_FILE:-$config_dir/gitea.env}"

printf 'Gitea username [%s]: ' "$default_username" >&3
IFS= read -r username <&3
username=${username:-$default_username}

printf 'Gitea password (input hidden): ' >&3
IFS= read -r -s password <&3
printf '\n' >&3
exec 3>&-

if [ -z "$username" ] || [ -z "$password" ]; then
  unset password
  echo "Username and password must not be empty; nothing was written" >&2
  exit 1
fi

mkdir -p "$config_dir"
chmod 700 "$config_dir"
umask 077
temp_file=$(mktemp "$config_dir/.gitea.env.XXXXXX")
cleanup() {
  rm -f "$temp_file"
}
trap cleanup EXIT

{
  printf '# Generated by scripts/security/store-gitea-account.sh\n'
  printf 'export GITEA_URL=%q\n' "$default_url"
  printf 'export GITEA_USERNAME=%q\n' "$username"
  printf 'export GITEA_PASSWORD=%q\n' "$password"
} > "$temp_file"
unset password

chmod 600 "$temp_file"
mv -f "$temp_file" "$env_file"
trap - EXIT

install_shell_hook() {
  local bashrc="$HOME/.bashrc"
  local begin_marker="# >>> myblog gitea credentials >>>"
  local end_marker="# <<< myblog gitea credentials <<<"
  touch "$bashrc"
  chmod 600 "$bashrc"
  if grep -Fq "$begin_marker" "$bashrc"; then
    return
  fi
  {
    printf '\n%s\n' "$begin_marker"
    printf 'if [ -r "$HOME/.config/myblog/gitea.env" ]; then\n'
    printf '  . "$HOME/.config/myblog/gitea.env"\n'
    printf 'fi\n'
    printf '%s\n' "$end_marker"
  } >> "$bashrc"
}

if [ "$env_file" = "$config_dir/gitea.env" ] \
    && [ "${GITEA_INSTALL_SHELL_HOOK:-1}" != "0" ]; then
  install_shell_hook
fi

echo "Gitea credentials written to $env_file"
echo "File mode: $(stat -c '%a' "$env_file")"
if [ "$env_file" = "$config_dir/gitea.env" ] \
    && [ "${GITEA_INSTALL_SHELL_HOOK:-1}" != "0" ]; then
  echo "New Bash terminals will load the variables automatically."
  echo "Load them into the current terminal with:"
  echo "  source ~/.bashrc"
fi
